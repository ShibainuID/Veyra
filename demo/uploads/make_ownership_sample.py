"""Generate demo/uploads/sari-ownership-sample.pdf: a clearly marked SAMPLE ownership certificate for the demo cow.

Every name in it is the demo's own fiction (Wahyu Farms, W. Santoso, Sari, animal-demo-001; demo/fixtures/herd.json
and enrollment_samples.json). It is not a real registry document and certifies nothing.

    uv run --no-project --with fpdf2==2.8.3 python demo/uploads/make_ownership_sample.py
"""

from pathlib import Path

from fpdf import FPDF

OUT = Path(__file__).with_name("sari-ownership-sample.pdf")
INK = (32, 33, 36)
MUTED = (96, 98, 104)
WATERMARK = (200, 52, 36)
WATERMARK_SOFT = (246, 196, 188)

FIELDS = [
    ("Animal", "Sari"),
    ("VEYRA passport ID", "animal-demo-001"),
    ("Breed", "Bali cattle (beef)"),
    ("Sex", "Female"),
    ("Registered owner", "Wahyu Farms (fictional demo farm)"),
    ("Owner's representative", "W. Santoso, farm manager (fictional)"),
    ("Acquired", "Bred on farm"),
    ("Identification", "Muzzle reference enrolled in VEYRA from a guided phone video"),
    ("Certificate no.", "SAMPLE-OWN-0001"),
    ("Issued", "20 October 2026"),
]


def build() -> FPDF:
    pdf = FPDF(format="A4")
    pdf.set_title("SAMPLE ownership certificate - Sari (demo document)")
    pdf.set_author("VEYRA demo kit")
    pdf.set_subject("Fictional sample document for the VEYRA demo; not a real certificate")
    pdf.set_auto_page_break(False)
    pdf.add_page()

    # Watermark first, so the text prints over it.
    pdf.set_text_color(*WATERMARK_SOFT)
    pdf.set_font("Helvetica", "B", 40)
    mark = "SAMPLE - demo document"
    width = pdf.get_string_width(mark)
    with pdf.rotation(35, x=105, y=150):
        pdf.text(105 - width / 2, 157, mark)

    pdf.set_draw_color(*INK)
    pdf.set_line_width(1.2)
    pdf.rect(12, 12, 186, 273)

    pdf.set_text_color(*WATERMARK)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_xy(20, 20)
    pdf.cell(170, 8, "SAMPLE - DEMO DOCUMENT - NOT A REAL CERTIFICATE", align="C")

    pdf.set_text_color(*INK)
    pdf.set_font("Helvetica", "B", 24)
    pdf.set_xy(20, 36)
    pdf.cell(170, 12, "Certificate of livestock ownership", align="C")
    pdf.set_font("Helvetica", "", 12)
    pdf.set_text_color(*MUTED)
    pdf.set_xy(20, 50)
    pdf.cell(170, 7, "Fictional sample prepared for the VEYRA hackathon demo", align="C")

    y = 72
    pdf.set_line_width(0.6)
    pdf.line(24, y - 4, 186, y - 4)
    for label, value in FIELDS:
        pdf.set_xy(24, y)
        pdf.set_font("Helvetica", "", 11)
        pdf.set_text_color(*MUTED)
        pdf.cell(58, 8, label)
        pdf.set_font("Helvetica", "B", 12)
        pdf.set_text_color(*INK)
        pdf.multi_cell(104, 8, value)
        y = max(y + 12, pdf.get_y() + 4)
        pdf.set_line_width(0.2)
        pdf.line(24, y - 2, 186, y - 2)

    pdf.set_xy(24, y + 8)
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(*INK)
    pdf.multi_cell(162, 6, (
        "This sample states that the animal above belongs to the farm named. In the VEYRA demo, uploading it to "
        "the animal's passport as an Ownership document adds an ownership reference, which the sample "
        "Mortality + Theft product requires. It carries no legal weight, names no real person or organization, "
        "and must not be used outside the demo."))

    pdf.set_xy(24, 250)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*MUTED)
    pdf.cell(80, 6, "Signed: W. Santoso (fictional)")
    pdf.cell(82, 6, "Registry stamp: none - sample", align="R")
    pdf.set_xy(20, 268)
    pdf.set_text_color(*WATERMARK)
    pdf.set_font("Helvetica", "B", 10)
    pdf.cell(170, 6, "SAMPLE - demo document - generated by demo/uploads/make_ownership_sample.py", align="C")
    return pdf


if __name__ == "__main__":
    build().output(str(OUT))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
